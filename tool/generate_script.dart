// Embeds js/k_html_dark_mode.js into lib/src/generated/script_source.g.dart.
//
//     dart run tool/generate_script.dart
//
// A pure Dart package cannot read its own files at runtime on every platform
// (a Flutter release build has no package directory to read from), so the
// script ships as a string constant. test/script_sync_test.dart fails when the
// constant and the source drift apart.
import 'dart:io';

const _source = 'js/k_html_dark_mode.js';
const _target = 'lib/src/generated/script_source.g.dart';

void main() {
  final js = File(_source).readAsStringSync().replaceAll('\r\n', '\n');

  // Each of these would break the output: the first ends the Dart raw string,
  // the other two end or derail the inline <script> element in the page.
  const forbidden = {
    "'''": 'three consecutive single quotes end the Dart raw string',
    '</script': 'a closing script tag ends the inline <script> element',
    '<!--': 'an HTML comment opener switches the <script> parser state',
  };
  forbidden.forEach((needle, why) {
    final at = js.indexOf(needle);
    if (at != -1) {
      final line = '\n'.allMatches(js.substring(0, at)).length + 1;
      stderr.writeln('error: $_source:$line contains "$needle" — $why.');
      exit(1);
    }
  });

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_script.dart from $_source.')
    ..writeln('// Do not edit by hand: edit the JavaScript and regenerate.')
    ..writeln()
    ..writeln('/// The in-page pass, verbatim from `$_source`.')
    ..write("const String kdmScriptSource = r'''")
    ..write(js)
    ..writeln("''';");

  File(_target)
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());
  stdout.writeln('wrote $_target (${js.length} chars)');
}
